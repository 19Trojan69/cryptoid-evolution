// Bake the existing, unmodified material function once at build time. The game
// requests individual PNGs; it never downloads or decodes the entire catalogue.
import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { allPlayerColors, playerSkins } from '../src/pages/shipFleet.ts';
import { paintShipMaterial } from '../src/pages/shipMaterial.ts';
import { namedShipAccent } from '../src/pages/shipIdentityColor.ts';
import { shipEvolutionAsset } from '../src/pages/shipEvolution.ts';

const require = createRequire(import.meta.url);
const canvasPackage = '@napi-rs/canvas';
const { createCanvas, loadImage } = require(canvasPackage);
const canvasVersion = require(`${canvasPackage}/package.json`).version;
export const frontendRoot = new URL('../', import.meta.url);

export async function buildPaintedHulls({ check = false } = {}) {
  const hash = createHash('sha256').update(`painted-hulls-v1|${canvasVersion}`);
  hash.update(await readFile(new URL(import.meta.url)));
  for (const name of ['shipMaterial.ts', 'shipTint.ts', 'shipIdentityColor.ts', 'shipFleet.ts', 'shipEvolution.ts']) {
    hash.update(await readFile(new URL(`src/pages/${name}`, frontendRoot)));
  }
  const sources = [];
  for (let sprite = 0; sprite < playerSkins.length; sprite++) for (const stage of [1, 2, 3]) {
    const url = shipEvolutionAsset(sprite, stage);
    const data = await readFile(new URL(`public${url}`, frontendRoot));
    hash.update(data);
    sources.push({ sprite, stage, data });
  }
  const revision = hash.digest('hex').slice(0, 20);
  const destination = new URL(`public/ships/painted/${revision}/`, frontendRoot);
  if (!check) await mkdir(destination, { recursive: true });
  const encodedBytes = [];
  let totalBytes = 0;
  for (const { sprite, stage, data } of sources) {
    const image = await loadImage(data);
    const canvas = createCanvas(image.width, image.height);
    try {
      const context = canvas.getContext('2d');
      context.drawImage(image, 0, 0);
      const original = context.getImageData(0, 0, image.width, image.height);
      for (const color of allPlayerColors) {
        const pixels = context.createImageData(image.width, image.height);
        pixels.data.set(original.data);
        const target = [1, 3, 5].map(offset => parseInt(color.glow.slice(offset, offset + 2), 16));
        paintShipMaterial(pixels.data, image.width, image.height, target, namedShipAccent(sprite));
        context.putImageData(pixels, 0, 0);
        const png = canvas.toBuffer('image/png');
        const name = `ship_${String(sprite + 1).padStart(2, '0')}_stage_${stage}_${color.id}.png`;
        const output = new URL(name, destination);
        if (check) {
          if (!(await readFile(output)).equals(png)) throw new Error(`Stale painted hull: ${name}`);
        } else await writeFile(output, png);
        encodedBytes.push(png.length);
        totalBytes += png.length;
      }
    } finally { canvas.width = canvas.height = 0; }
  }
  const manifest = '// Generated by scripts/buildPaintedHulls.mjs; do not edit by hand.\n'
    + `export const paintedHullRevision = ${JSON.stringify(revision)};\n`
    + `export const paintedHullColors: readonly string[] = ${JSON.stringify(allPlayerColors.map(c => c.id))};\n`
    + `export const paintedHullCount = ${playerSkins.length};\n`
    + `export const paintedHullBytes: readonly number[] = ${JSON.stringify(encodedBytes)};\n`;
  const manifestPath = new URL('src/generated/paintedHullManifest.ts', frontendRoot);
  if (check) {
    if (await readFile(manifestPath, 'utf8') !== manifest) throw new Error('Stale painted hull manifest');
  } else {
    await mkdir(new URL('src/generated/', frontendRoot), { recursive: true });
    await writeFile(manifestPath, manifest);
    // This ignored directory belongs to this generator. Retire only prior
    // generated hash directories after the replacement catalogue is complete.
    // Unknown names/files are preserved. Original ship artwork is elsewhere.
    const generatedRoot = new URL('public/ships/painted/', frontendRoot);
    for (const entry of await readdir(generatedRoot, { withFileTypes: true })) {
      if (entry.isDirectory() && /^[a-f0-9]{20}$/.test(entry.name) && entry.name !== revision) {
        const obsolete = new URL(`${entry.name}/`, generatedRoot);
        for (let attempt = 0; attempt < 3; attempt++) {
          await rm(obsolete, { recursive: true, force: true, maxRetries: 3 });
          const remains = await readdir(obsolete).then(() => true, error => {
            if (error.code === 'ENOENT') return false;
            throw error;
          });
          if (!remains) break;
          if (attempt === 2) throw new Error(`Obsolete generated hull directory was not removed: ${entry.name}`);
        }
      }
    }
  }
  return { revision, variants: encodedBytes.length, totalBytes, dimensions: 'original', canvasVersion };
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  console.log(JSON.stringify(await buildPaintedHulls({ check: process.argv.includes('--check') })));
}
