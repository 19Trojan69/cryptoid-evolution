export function bossImageSpecs(config: Pick<BossConfig, 'id' | 'image' | 'weaponImage'>): readonly ImageSpec[] {
  const sizes = originalBossDimensions[config.id - 1];
  if (!Number.isInteger(config.id) || !sizes) throw new RangeError('Missing released boss texture dimensions');
  return [
    { url: config.image, maxWidth: sizes[0], maxHeight: sizes[1], maxEncodedBytes: sizes[2] },
    { url: config.weaponImage, maxWidth: sizes[3], maxHeight: sizes[4], maxEncodedBytes: sizes[5] },
  ];
}
